function walk(dir, acc = []) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = path.join(dir, ent.name).slice(srcRoot.length + 1).replace(/\\/g, "/");
    if (ent.isDirectory()) {
      if (ent.name === "node_modules") continue;
      walk(path.join(dir, ent.name), acc);
    } else if (/\.(css|tsx|ts)$/.test(ent.name) && !SKIP_FILES.has(rel)) {
      acc.push(path.join(dir, ent.name));
    }
  }
  return acc;
}

let totalChanges = 0;
for (const file of walk(srcRoot)) {
  let text = fs.readFileSync(file, "utf8");
  const before = text;
  for (const [from, to] of REPLACEMENTS) {
    if (text.includes(from)) {
      text = text.split(from).join(to);
    }
  }
  if (text !== before) {
    fs.writeFileSync(file, text, "utf8");
    totalChanges++;
    console.log("updated:", path.relative(srcRoot, file));
  }
}
console.log("files updated:", totalChanges);
